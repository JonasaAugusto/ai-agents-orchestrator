AVISO_SEM_CANAL = doctor.AVISO_SEM_CANAL


def _toml_str(v: str) -> str:
    return json.dumps(str(v), ensure_ascii=False)


def gerar_toml(r: dict) -> str:
    """Builds config.toml from the wizard answers (no secrets in here)."""
    linhas = ["# ai-agents-orchestrator configuration (generated by `aao setup`). See examples/config.example.toml.",
              f"mode = {_toml_str(r.get('mode', 'full'))}",
              "", "[service]", f"channel = {_toml_str(r['channel'])}", f"user = {_toml_str(r['user'])}",
              f"timezone = {_toml_str(r['timezone'])}", f"orchestrator = {_toml_str(r.get('orchestrator', 'claude'))}",
              "", "[paths]", f"state_dir = {_toml_str(r['state_dir'])}",
              f"claude_transcripts = {_toml_str(r['claude_transcripts'])}", "",
              *(["[lite]", f"transcripts_project = {_toml_str(r['transcripts_project'])}", ""]
                if r.get("transcripts_project") else []), "[codex]",
              f"network_access = {'true' if r.get('codex_full') else 'false'}",
              f"full_access = {'true' if r.get('codex_full') else 'false'}  # DANGER: true disables the Codex sandbox",
              f"full_access_read_only = {'true' if r.get('codex_full') else 'false'}  # also read-only phases", "",
              "[claude]", "wakeup_enabled = false  # EXPERIMENTAL", ""]
    if r["channel"] == "telegram":
        linhas += ["[telegram]", f"chat_id = {int(r['chat_id'])}", ""]
    if r["channel"] == "whatsapp":
        linhas += ["[whatsapp]", f"accept_unofficial_risk = {'true' if r.get('accept_risk') else 'false'}",
                   f"owner_number = {_toml_str(r['owner_number'])}", "max_messages_per_minute = 12", ""]
    linhas += ["[publish]", "push_allowlist = [" + ", ".join(_toml_str(g) for g in r["allowlist"]) + "]", ""]
    for nome, spec in r["repos"].items():
        linhas.append(f"[repos.{nome}]")
        for k, v in spec.items():
            linhas.append(f"{k} = " + (str(v).lower() if isinstance(v, bool) else _toml_str(v)))
        linhas.append("")
    return "\n".join(linhas)


def _gid(usuario: str) -> int | None:
    import grp
    try:
        return grp.getgrnam(usuario).gr_gid
    except KeyError:
        return None


def gravar(caminho: Path, texto: str, modo: int, dono_root: bool = True, grupo: int | None = None) -> None:
    if compat.WINDOWS:
        from .lite import write_private
        write_private(caminho, texto)
        return
    caminho.parent.mkdir(parents=True, exist_ok=True)
    tmp = caminho.with_suffix(caminho.suffix + ".tmp")
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, modo)
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write(texto)
    os.chmod(tmp, modo)
    if dono_root and compat.euid() == 0:
        os.chown(tmp, 0, 0 if grupo is None else grupo)
    os.replace(tmp, caminho)


class Assistente:
    def __init__(self, entrada=input, saida=print, config_file: Path | None = None, env_file: Path | None = None,
                 parear=None, amb=None):
        self.entrada, self.saida = entrada, saida
        self.config_file = config_file or config.default_config_file()
        self.env_file = env_file or config.ENV_FILE
        self.parear = parear  # callable(cfg_answers) for WhatsApp pairing; None = real neonize pairing
        self.amb = amb or doctor.Ambiente()
        self.explicit_config = config_file is not None or bool(os.environ.get("AAO_CONFIG"))

    def configurar_clis(self, cfg):
        """Official status/installation commands only; never inspect authentication files."""
        for item in doctor.checar_codex(cfg, self.amb):
            self.saida(f"{item.nome}: {item.estado}. {item.correcao}")
        if not self.amb.which(cfg.claude_bin):
            self.saida("Claude Code not found; install it, then rerun aao setup to install the plugin.")
            return
        code, _ = self.amb.rodar([cfg.claude_bin, "auth", "status"], env=None)
        self.saida("Claude Code login: " + ("ok" if code == 0 else "not confirmed; run claude auth login"))
        # O plugin só é (re)instalado quando falta ou mudou de versão, e só com a confirmação da pessoa.
        marca = cfg.state_dir / "plugin-instalado"
        try:
            instalado = marca.read_text(encoding="utf-8").strip()
        except OSError:
            instalado = ""
        if instalado == __version__:
            self.saida(f"Claude plugin already installed ({__version__}); nothing changed.")
            return
        if not self.sim("Install/update the Claude Code plugin for your user (claude plugin install --scope user)?", True):
            self.saida("Plugin not installed; rerun aao setup whenever you want it.")
            return
        ok = True
        for cmd in ([cfg.claude_bin, "plugin", "marketplace", "add", "JonasaAugusto/ai-agents-orchestrator"],
                    [cfg.claude_bin, "plugin", "install", "ai-agents-orchestrator@ai-agents-orchestrator", "--scope", "user"]):
            code, _ = self.amb.rodar(cmd, timeout=120)
            ok = ok and code == 0
            self.saida("Claude plugin " + ("ready" if code == 0 else "command failed; retry aao setup after checking Claude Code"))
        if ok:
            try:
                marca.parent.mkdir(parents=True, exist_ok=True)
                marca.write_text(__version__, encoding="utf-8")
            except OSError:
                pass

    def pergunta(self, texto: str, padrao: str = "", valida=None) -> str:
        while True:
            r = (self.entrada(f"{texto}{f' [{padrao}]' if padrao else ''}: ") or "").strip() or padrao
            if valida is None or valida(r):
                return r
            self.saida("  invalid value, try again")

    def sim(self, texto: str, padrao: bool = False) -> bool:
        r = self.pergunta(texto + (" (Y/n)" if padrao else " (y/N)"), "y" if padrao else "n").lower()
        return r.startswith("y") or r.startswith("s")

    def executar(self) -> int:
        s = self.saida
        if self.config_file.is_file():
            s(f"Keeping existing configuration {self.config_file}; edit it explicitly to change modes or repositories.")
            cfg = config.carregar({}, self.config_file)
            if cfg.mode == "lite":
                doctor.corrigir_triviais(cfg)
            self.configurar_clis(cfg)
            return 0
        s("ai-agents-orchestrator setup. Nothing secret is printed; lite uses current-user file permissions.\n")
        r: dict = {"repos": {}, "allowlist": []}
        r["mode"] = self.pergunta("Runtime mode? lite (current user, no systemd) / full (Linux root daemon)", "lite",
                                   lambda v: v in ("lite", "full"))
        lite = r["mode"] == "lite"
        if not lite and not sys.platform.startswith("linux"):
            s("Full mode requires Linux and systemd. Choose lite on macOS or Windows.")
            return 2
        if not lite and not self.explicit_config:
            self.config_file = Path(f"/etc/{config.NOME}/config.toml")
        if lite:
            if self.config_file == Path(f"/etc/{config.NOME}/config.toml"):
                self.config_file = config.user_config_dir() / "config.toml"
            r["user"] = getpass.getuser()
        else:
            r["user"] = self.pergunta("Service user (unprivileged, runs the service and Codex)", "aao")
        state = str(compat.user_state_dir()) if lite else f"/var/lib/{config.NOME}"
        r["state_dir"] = self.pergunta("State directory", state)
        r["timezone"] = self.pergunta("Timezone (IANA name)", "UTC")
        r["claude_transcripts"] = self.pergunta("Claude Code project transcripts dir to mirror",
                                                str(Path.home() / ".claude" / "projects" / ("" if lite else "-root")))
        if lite:
            r["transcripts_project"] = self.pergunta(
                "Project folder whose Claude Code transcripts to mirror (full path; empty = the folder where aao serve runs)", "")
        r["orchestrator"] = self.pergunta("Who coordinates the work? claude / codex (the other executes and reviews)", "claude",
                                          lambda v: v.lower() in ("claude", "codex")).lower()
        s("\nCodex permissions. 'restricted' keeps Codex in its sandbox, without network, in throwaway clones (safest). "
          "'full' gives Codex the same permissions as Claude: no sandbox, network on, every phase. Choose 'full' only on "
          "your own machine, with repositories you trust; publishing still needs your approval either way.")
        r["codex_full"] = self.pergunta("Codex permissions? restricted / full", "restricted",
                                        lambda v: v.lower() in ("restricted", "full")).lower() == "full"
        canal = "none" if lite else self.pergunta("Which chat channel? telegram / none / whatsapp (unofficial extra, risk of number ban)", "telegram",
                                                   lambda v: v.lower() in ("telegram", "whatsapp", "none"))
        r["channel"] = canal.lower()
        env: dict[str, str] = {}
        if r["channel"] == "none":
            s("\nNOTE: " + AVISO_SEM_CANAL + "\n")
        elif r["channel"] == "telegram":
            s("\nTelegram: 1) talk to @BotFather, send /newbot and copy the token; 2) send any message to @userinfobot "
              "to get YOUR numeric user id. Only that user, in a private chat, will ever be answered.")
            env["AAO_TELEGRAM_TOKEN"] = self.pergunta("Bot token", valida=lambda v: bool(re.fullmatch(r"\d{5,}:[\w-]{20,}", v)))
            r["chat_id"] = self.pergunta("Your Telegram user id", valida=lambda v: v.isdigit())
        else:
            from .whatsapp import AVISO_RISCO
            if not self.amb.modulo("neonize"):
                s("\nWhatsApp is an optional extra and is not installed: pip install 'ai-agents-orchestrator[whatsapp] @ git+https://github.com/JonasaAugusto/ai-agents-orchestrator'")
            s("\n" + "!" * 78 + "\n" + AVISO_RISCO + "\n" + "!" * 78)
            if self.pergunta("Type I ACCEPT THE RISK to continue with WhatsApp (anything else switches to none)") != "I ACCEPT THE RISK":
                r["channel"] = "none"
                s("WhatsApp not enabled. " + AVISO_SEM_CANAL)
            else:
                r["accept_risk"] = True
                r["owner_number"] = self.pergunta("YOUR WhatsApp number (the only one the bot talks to), digits only, "
                                                  "with country code", valida=lambda v: v.isdigit() and len(v) >= 8)
        s("\nRepositories Codex may work on (empty name to finish).")
        while True:
            nome = self.pergunta("Repo short name", "")
            if not nome:
                break
            if not re.fullmatch(r"[A-Za-z0-9._-]+", nome):
                s("  use letters, digits, '.', '_' or '-'")
                continue
            gh = self.pergunta("GitHub owner/repo (empty for a local-only repo)", "")
            spec: dict[str, object] = {"base_branch": self.pergunta("Base branch", "main")}
            if gh:
                spec["github"] = gh
                if self.sim("Allow approved interactive publishing to it?" if lite else
                            "Allow the root daemon to push agent branches / approved merges to it?", True):
                    r["allowlist"].append(gh)
            else:
                spec["source"] = self.pergunta("Local git checkout path")
                if lite:
                    spec["local"] = True
            r["repos"][nome] = spec
        if lite:
            gravar(self.config_file, gerar_toml(r), 0o600, dono_root=False)
            cfg = config.carregar({}, self.config_file)
            doctor.corrigir_triviais(cfg)
            self.configurar_clis(cfg)
            from .lite import diagnostico_transcripts
            estado, msg, fix = diagnostico_transcripts(cfg)
            s(f"Transcripts: {estado}. {msg}" + (f" {fix}" if fix else ""))
            s("Lite: same user as your engines; no isolation or Publish button. Approval: aao publish <id> (ID SHA).")
            s("Next: aao doctor; run aao serve in a terminal. No sudo or systemd needed.")
            return 0
        env["AAO_PUBLISH_KEY"] = secrets.token_hex(32)
        gid = _gid(r["user"])
        modo_cfg = 0o640 if gid is not None else 0o600
        gravar(self.config_file, gerar_toml(r), modo_cfg, grupo=gid)
        gravar(self.env_file, "".join(f"{k}={v}\n" for k, v in env.items()), 0o600)
        gravar(self.env_file.parent / "publish.key", env["AAO_PUBLISH_KEY"] + "\n", 0o600)  # read by the root daemon
        s(f"\nWrote {self.config_file} ({modo_cfg:04o}" + ("" if gid is not None else
          f"; after creating the user run: chgrp {r['user']} {self.config_file} && chmod 640 {self.config_file}")
          + f"), {self.env_file} and {self.env_file.parent / 'publish.key'} (0600).")
        if r["channel"] == "whatsapp":
            self._parear(r)
        self.configurar_clis(config.carregar({}, self.config_file))
        s("\nNext steps:")
        s(f"  1. Codex login (official command, as the service user): "
          f"sudo -u {r['user']} env HOME={r['state_dir']} CODEX_HOME={r['state_dir']}/.codex codex login --device-auth")
        s("  2. Claude Code: install the plugin from claude-plugin/ (or the hooks in examples/claude-hooks.json).")
        s(f"  3. Run `{CLI} doctor` and fix anything it reports; then enable the systemd units (see README).")
        return 0

    def _parear(self, r: dict) -> None:
        if self.parear:
            self.parear(r)
            return
        try:  # pragma: no cover - needs the optional library and a phone
            from . import whatsapp
            cli = whatsapp._ClienteNeonize(Path(r["state_dir"]) / "whatsapp")
            if self.sim("Pair with a pairing code instead of a QR code?", True):
                self.saida("Pairing code (WhatsApp > Linked devices > Link with phone number): "
                           + cli.parear_codigo(r["owner_number"]))
            else:
                self.saida("A QR code will be printed; scan it in WhatsApp > Linked devices. Ctrl+C when paired.")
            cli.connect()
        except Exception as e:  # pragma: no cover
            self.saida(f"Pairing not done ({type(e).__name__}). Install the extra and run `{CLI} setup` again.")


def nao_interativo(destino: Path, fonte: Path | None = None) -> int:
    """Write a local evaluation config only; never infer a production path or create credentials."""
    # Check before resolve(), otherwise an existing symlink would be silently followed.
    if destino.is_symlink() or (destino.exists() and (not destino.is_dir() or any(destino.iterdir()))):
        print("setup refused: --output-dir must be a new or empty directory, not a symlink")
        return 1
    destino = destino.resolve()
    fonte = fonte.resolve() if fonte is not None else None
    if fonte is not None and not (fonte.is_dir() and (fonte / ".git").exists()):
        print("setup refused: --repo-source must be a local Git checkout")
        return 1
    destino.mkdir(parents=True, exist_ok=True, mode=0o700)
    if compat.WINDOWS:
        usuario = getpass.getuser()
    else:
        import pwd
        usuario = pwd.getpwuid(os.geteuid()).pw_name
    texto = gerar_toml({"channel": "none", "user": usuario, "timezone": "UTC",
                        "state_dir": str(destino / "state"), "claude_transcripts": str(destino / "transcripts"),
                        "allowlist": [], "repos": {"demo": {"source": str(fonte), "base_branch": "main", "local": True}}
                        if fonte else {}})
    caminhos = {"root_state_dir": "root-state", "claude_memory": "memory", "claude_sessions": "sessions",
                "rules_file": "BASE_RULES.md", "division_file": "DIVISION.md", "templates_dir": "templates",
                "socket": "cli.sock", "root_socket": "root.sock"}
    extras = "".join(f"{key} = {_toml_str(str(destino / value))}\n" for key, value in caminhos.items())
    texto = texto.replace("[paths]\n", "[paths]\n" + extras)
    texto = texto.replace("[publish]\n", "[publish]\n" +
                          f"manifest = {_toml_str(str(destino / 'publish.json'))}\n" +
                          f"key_file = {_toml_str(str(destino / 'publish.key'))}\n")
    if compat.WINDOWS:
        # Sem uid POSIX nem O_DIRECTORY/O_NOFOLLOW: a pasta está vazia e foi criada agora; restringe a DACL e cria exclusivo.
        try:
            compat.private(destino)
            with open(destino / "config.toml", "x", encoding="utf-8") as stream:
                stream.write(texto)
            compat.private(destino / "config.toml")
        except OSError:
            print("setup refused: could not exclusively create config.toml; existing files were preserved")
            return 1
    else:
        # This evaluation mode may run in CI as root. Never truncate or replace a
        # file inserted after the empty-directory check, and anchor writes to the fd.
        try:
            directory = os.open(destino, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
            try:
                st = os.fstat(directory)
                if st.st_uid != os.geteuid() or st.st_mode & 0o022:
                    print("setup refused: --output-dir must be owned by the current user and not writable by group/others")
                    return 1
                fd = os.open("config.toml", os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600, dir_fd=directory)
                with os.fdopen(fd, "w", encoding="utf-8") as stream:
                    stream.write(texto)
            finally:
                os.close(directory)
        except OSError:
            print("setup refused: could not exclusively create config.toml; existing files were preserved")
            return 1
    print("Created isolated config.toml (0600); channel=none, sandbox=workspace-write, publishing disabled.")
    print("No login, user, secret, service or plugin installation was performed. Run aao doctor with AAO_CONFIG.")
    return 0


def main() -> int:  # pragma: no cover - interactive
    try:
        return Assistente().executar()
    except (KeyboardInterrupt, EOFError):
        print("\nsetup cancelled; nothing else was written")
        return 1
